import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, unlinkSync } from 'node:fs';
import { join } from 'node:path';
import { expect } from 'e2e';
import { test } from '../fixtures.js';

test('All history renders the actual bundled Bitcoin archive from 2010', { tags: ['core', 'providers'] }, async ({ start, screen, agent, app }) => {
  await start('ready-crypto');
  const bitcoin = screen.getByRole('button', /^Bitcoin,/i);
  await expect(bitcoin).toHaveAccessibleName('Bitcoin, 0.00002');
  const udid = process.env.CURRENCY_E2E_UDID!;
  const directory = execFileSync('xcrun', ['simctl', 'get_app_container', udid, 'com.dimasike.currency', 'group.com.dimasike.currency.shared'], { encoding: 'utf8' }).trim();
  const cache = join(directory, 'history-v3-BTC-USD-0.json');
  if (existsSync(cache)) unlinkSync(cache);
  await bitcoin.longPress({ duration: 650 });
  await expect(screen.getByRole('button', 'Details & history', { exact: true })).toBeVisible();
  await screen.getByRole('button', 'Details & history', { exact: true }).tap();
  await expect(screen.getByTestId('currency.details.BTC')).toBeVisible();
  const all = screen.getByTestId('currency.details.historyRange').getByRole('tab', 'All available history', { exact: true });
  await all.tap();
  await expect(all).toBeSelected();
  const source = screen.getByTestId('currency.details.sourceDisclosure').filter({ hasText: /Coin Metrics/ });
  await expect(source).toHaveAccessibleName('Coin Metrics + Fawaz');
  await expect(source).toBeVisible();
  assert.ok(existsSync(cache));
  const saved = JSON.parse(readFileSync(cache, 'utf8')) as { points: { date: number; value: number }[]; source: { provider: object; observation: string; contributingProviders?: object[] } };
  assert.deepEqual(saved.source.provider, { fawaz: {} });
  assert.equal(saved.source.observation, 'monthlyReference');
  assert.deepEqual(saved.source.contributingProviders, [{ coinMetrics: {} }]);
  assert.ok(saved.points.length >= 190);
  assert.equal(new Date((saved.points[0]!.date + 978_307_200) * 1000).getUTCFullYear(), 2010);
  assert.ok(saved.points.every(point => point.value > 0 && Number.isFinite(point.value)));
  await agent.waitFor('Bitcoin All history is selected and a readable historical line chart spans from around 2010 to the current quote. The current quote is 50,000 USD and the source identifies Coin Metrics and Fawaz.', { vision: 'only', timeout: 30_000 });
  await app.screenshot('bitcoin-actual-bundled-all-history-from-2010');
  await source.tap();
  await expect(source).toHaveValue('Expanded');
  const firstDate = new Intl.DateTimeFormat('en-US', { year: 'numeric', month: 'short', day: 'numeric', timeZone: 'UTC' })
    .format(new Date((saved.points[0]!.date + 978_307_200) * 1000));
  await expect(screen.getByText(new RegExp(`^${firstDate} – `))).toBeVisible();
  await expect(screen.getByText(/^Saved /)).toBeVisible();
  const explanation = 'All shows all history available from this provider for this pair, grouped monthly. It may begin after the currency launched.';
  await agent.act(`Scroll down in Bitcoin Details until the exact text "${explanation}" is fully visible. Keep the source disclosure expanded.`);
  await expect(screen.getByText(explanation, { exact: true })).toBeVisible();
  await app.screenshot('bitcoin-actual-bundled-all-history-source-dates');
});
